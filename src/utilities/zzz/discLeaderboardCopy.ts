export type DiscCopyKey = keyof typeof copy;
export function discText(
  locale: string | undefined,
  key: DiscCopyKey,
  values: Record<string, string | number> = {},
): string {
  const code = normalizeZzzLocale(locale),
    index = DISC_LOCALES.indexOf(code as (typeof DISC_LOCALES)[number]);
  return copy[key][Math.max(0, index)].replace(/\{(\w+)\}/g, (_, name) =>
    String(values[name] ?? `{${name}}`),
  );
}
export function discLocalizations(key: DiscCopyKey): LocalizationMap {
  const locales = ["en-US", "zh-TW", "zh-CN", "ja", "ko", "fr", "vi"];
  return Object.fromEntries(
    DISC_LOCALES.map((locale, index) => [
      locales[index],
      discText(locale, key),
    ]),
  );
}
export const discCopyKeys = Object.keys(copy) as DiscCopyKey[];
export function discContent(locale: string | undefined, key: DiscCopyKey, values: Record<string, string | number> = {}): string {
  return messageSubtext(discText(locale, key, values));
}
