export function eventTitle(event: NewsEvent, locale: NewsLocale): string {
  const c = COPY[locale];
  return event.kind === "article"
    ? event.title
    : {
        update: c.statusUpdate,
        preload: c.statusPreload,
        maintenance_start: c.statusStart,
        maintenance_end: c.statusEnd,
      }[event.kind];
}

