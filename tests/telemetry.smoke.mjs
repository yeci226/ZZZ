import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const { TelemetryStore, combineRuntimeWorkers, combineSnapshots, taipeiDay, dailyPayload } = await import(pathToFileURL(resolve(process.argv[2])).href);
const dir = mkdtempSync(join(tmpdir(), 'bot-telemetry-test-'));
const DAY = 86400000;
const end = taipeiDay(1800000000000);
const start = end - DAY;
const db = new TelemetryStore(join(dir, 'test.sqlite'), start);
const other = new TelemetryStore(join(dir, 'test.sqlite'), start);
try {
  assert.equal(taipeiDay(end + 8 * 3600000), end);
  assert.equal(taipeiDay(end - 1), start);
  assert(db.begin('a', 'u1', 'g1', 'daily', start));
  assert(!other.begin('a', 'u1', 'g1', 'daily', start + 1));
  assert(other.begin('b', 'u1', 'g2', 'help', start + 1));
  assert(db.begin('c', 'u2', null, 'help', end - 1));
  assert(db.begin('next-day', 'u3', null, 'help', end));
  db.finish('a', 20, true);
  db.finish('b', 40, false);
  const guilds = Array.from({ length: 25 }, (_, i) => ({ id: String(i), name: '@everyone <test>', members: i + 1 }));
  const rows = [{ ready: true, session: 'a', shards: [0], guilds }, { ready: true, session: 'b', shards: [1], guilds }];
  const totals = combineSnapshots(rows, 2, 2);
  assert.equal(totals.servers, 25);
  assert.equal(totals.users, 325);
  assert.equal(totals.top.length, 20);
  assert.equal(totals.top[0].members, 25);
  assert.equal(combineSnapshots(rows.slice(0, 1), 2, 2), null);
  assert.equal(combineSnapshots([rows[0], rows[0]], 2, 2), null);
  assert.equal(combineSnapshots([{ ...rows[0], ready: false }, rows[1]], 2, 2), null);
  db.snapshot({ ...totals, time: start, servers: 30, users: 500 }, guilds.map(g => g.id));
  db.guildEvent('new', true, start + 5);
  other.guildEvent('new', true, start + 6);
  db.guildEvent('new', false, start + 7);
  db.snapshot({ ...totals, time: end - 1 }, guilds.map(g => g.id));
  const workers=combineRuntimeWorkers([{processKey:'1',runtime:{worker:0,rssBytes:100,restarts:0,eventLoopDelayMs:20,shards:[{shard:0}]}},{processKey:'1',runtime:{worker:1,rssBytes:100,restarts:1,eventLoopDelayMs:30,shards:[{shard:1}]}}]);
  assert.equal(workers.length,2);assert.equal(workers.filter(w=>w.resourceOwner).reduce((n,w)=>n+w.rssBytes,0),100);assert.equal(workers[0].processGroup,workers[1].processGroup);assert.equal(workers[1].resourceOwner,false);
  const stats = other.metrics(end);
  assert.equal(stats.totalCommands24h, 3);
  assert.equal(stats.totalCommands, 3);
  assert.equal(stats.totalUniqueUsers, 2);
  assert.equal(stats.uniqueUsers24h, 2);
  assert.equal(stats.uniqueServers24h, 2);
  assert.equal(stats.totalErrors24h, 1);
  assert.equal(stats.serversDelta24h, -5);
  assert.equal(stats.usersDelta24h, -175);
  assert.equal(stats.joinedServers24h, 1);
  assert.equal(stats.leftServers24h, 1);
  assert.equal(stats.complete, false); // missing snapshots are not claimed complete
  assert(db.claim('one', end));
  assert(!other.claim('two', end));
  assert(other.claim('two', end + 60000));
  const payload = dailyPayload('Bot', end, stats, totals.top);
  assert.deepEqual(payload.allowed_mentions.parse, []);
  assert.equal(payload.embeds.length, 3);
  assert(JSON.stringify(payload).length < 6000);
  const first = new TelemetryStore(join(dir, 'first.sqlite'), end - 100);
  assert.equal(first.metrics(end).serversDelta24h, null);
  assert.equal(first.metrics(end).complete, false);
  first.db.close();
  const commands=db.commandStats(start,end);
  assert.equal(commands.find(c=>c.name==='daily').errors,1);
  assert.equal(commands.find(c=>c.name==='help').unfinished,1);
  assert.equal(commands.find(c=>c.name==='help').p95Ms,40);
  assert.equal(commands.find(c=>c.name==='help').durationCount,1);
  db.buildRollups('zzz',end+180000);
  const rollup=db.db.prepare("SELECT * FROM rollups WHERE grain='day' AND start=?").get(start);
  assert.equal(JSON.parse(rollup.payload).stats.totalCommands24h,3);
  assert.equal(JSON.parse(rollup.payload).stats.windowStart,start);
  assert.equal(rollup.synced,0);
  db.finish('c',200,false);
  assert.equal(db.db.prepare("SELECT dirty FROM rollups WHERE grain='day' AND start=?").get(start).dirty,1);
  db.buildRollups('zzz',end+240000);
  const updated=JSON.parse(db.db.prepare("SELECT payload FROM rollups WHERE grain='day' AND start=?").get(start).payload);
  assert.equal(updated.stats.v2.commands.find(c=>c.name==='help').p95Ms,200);
  const before=db.db.prepare('SELECT count(*) n FROM rollups WHERE synced=0').get().n;
  db.cleanup(end + 8 * DAY);
  assert.equal(db.db.prepare('SELECT count(*) n FROM rollups WHERE synced=0').get().n,before);
  assert.equal(db.metrics(end + 8 * DAY).totalCommands, 4);
  assert.equal(db.metrics(end + 8 * DAY).totalUniqueUsers, 3);
  assert.equal(db.db.pragma('integrity_check', { simple: true }), 'ok');
  console.log('PASS telemetry: durable dedup, midnight, totals, deltas, shard coverage, top20, lease, retention');
} finally {
  db.db.close(); other.db.close(); rmSync(dir, { recursive: true, force: true });
}
